"""Builds the Synthboard icon from the Synthèse mark, so that it has one source.

The S of the mark is a waveform, and here it is also a swipe: one stroke across
a grid of keys, starting from a touch point. Writes the master SVG and the
Android adaptive icon. Run with `python3 -I tools/make-icon.py`.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(sys.argv[0]).resolve().parent.parent
MARK = ROOT / "docs/brand/synthese-mark.svg"

PETROL = "#0E5E68"
CLOUD = "#F2F0EA"
PARTIAL = "#63C0CB"

CANVAS = 108.0
SCALE = 0.60
KEY_COLUMNS, KEY_ROWS = 4, 3
KEY_WIDTH, KEY_HEIGHT, KEY_GAP = 11.0, 14.0, 2.6
STROKE = 13.5 * SCALE
TOUCH_RADIUS = 5.0
PARTIAL_STROKE = 2.2


def strokes():
    """The partials then the fundamental of the mark, as lists of points."""
    found = re.findall(r'<path class="([hf])" d="([^"]+)"', MARK.read_text("utf-8"))
    parsed = []
    for _, data in found:
        numbers = [float(n) for n in re.findall(r"-?\d+\.?\d*", data)]
        parsed.append(list(zip(numbers[0::2], numbers[1::2])))
    return parsed


def place(points):
    middle = CANVAS / 2
    return [(middle + (x - 64) * SCALE, middle + (y - 64) * SCALE) for x, y in points]


def path_data(points):
    head = points[0]
    rest = " ".join(f"L{x:.2f} {y:.2f}" for x, y in points[1:])
    return f"M{head[0]:.2f} {head[1]:.2f} {rest}"


def keys():
    width = KEY_COLUMNS * KEY_WIDTH + (KEY_COLUMNS - 1) * KEY_GAP
    height = KEY_ROWS * KEY_HEIGHT + (KEY_ROWS - 1) * KEY_GAP
    left, top = (CANVAS - width) / 2, (CANVAS - height) / 2
    return [
        (left + column * (KEY_WIDTH + KEY_GAP), top + row * (KEY_HEIGHT + KEY_GAP))
        for row in range(KEY_ROWS)
        for column in range(KEY_COLUMNS)
    ]


def rounded(x, y):
    radius = 2.6
    right, bottom = x + KEY_WIDTH, y + KEY_HEIGHT
    return (
        f"M{x + radius:.2f} {y:.2f} H{right - radius:.2f} Q{right:.2f} {y:.2f} {right:.2f} {y + radius:.2f} "
        f"V{bottom - radius:.2f} Q{right:.2f} {bottom:.2f} {right - radius:.2f} {bottom:.2f} "
        f"H{x + radius:.2f} Q{x:.2f} {bottom:.2f} {x:.2f} {bottom - radius:.2f} "
        f"V{y + radius:.2f} Q{x:.2f} {y:.2f} {x + radius:.2f} {y:.2f} Z"
    )


def main():
    first_partial, second_partial, fundamental = (place(points) for points in strokes())
    grid = " ".join(rounded(x, y) for x, y in keys())
    start = fundamental[0]
    touch = (
        f"M{start[0] - TOUCH_RADIUS:.2f} {start[1]:.2f} a{TOUCH_RADIUS} {TOUCH_RADIUS} 0 1 0 {2 * TOUCH_RADIUS} 0 "
        f"a{TOUCH_RADIUS} {TOUCH_RADIUS} 0 1 0 {-2 * TOUCH_RADIUS} 0 Z"
    )
    main_path = path_data(fundamental)
    partials = [path_data(first_partial), path_data(second_partial)]

    brand = ROOT / "docs/brand"
    brand.mkdir(parents=True, exist_ok=True)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS:.0f} {CANVAS:.0f}">
  <rect width="{CANVAS:.0f}" height="{CANVAS:.0f}" fill="{PETROL}"/>
  <path d="{grid}" fill="{CLOUD}" fill-opacity="0.10"/>
  <path d="{partials[0]}" fill="none" stroke="{PARTIAL}" stroke-opacity="0.55" stroke-width="{PARTIAL_STROKE}"/>
  <path d="{partials[1]}" fill="none" stroke="{PARTIAL}" stroke-opacity="0.55" stroke-width="{PARTIAL_STROKE}"/>
  <path d="{main_path}" fill="none" stroke="{CLOUD}" stroke-width="{STROKE:.2f}" stroke-linecap="round" stroke-linejoin="round"/>
  <path d="{touch}" fill="{PARTIAL}"/>
</svg>
"""
    (brand / "synthboard-icon.svg").write_text(svg, "utf-8")

    res = ROOT / "android/app/src/main/res"
    (res / "drawable").mkdir(parents=True, exist_ok=True)
    (res / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (res / "values").mkdir(parents=True, exist_ok=True)
    head = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/make-icon.py. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="108dp" android:height="108dp"\n    android:viewportWidth="{CANVAS:.0f}" android:viewportHeight="{CANVAS:.0f}">\n'
    )

    def stroke(data, color, width, alpha=None):
        opacity = f' android:strokeAlpha="{alpha}"' if alpha else ""
        return (
            f'    <path android:pathData="{data}" android:strokeColor="{color}"{opacity}\n'
            f'        android:strokeWidth="{width:.2f}" android:strokeLineCap="round" android:strokeLineJoin="round"/>\n'
        )

    foreground = (
        head
        + f'    <path android:pathData="{grid}" android:fillColor="{CLOUD}" android:fillAlpha="0.10"/>\n'
        + stroke(partials[0], PARTIAL, PARTIAL_STROKE, 0.55)
        + stroke(partials[1], PARTIAL, PARTIAL_STROKE, 0.55)
        + stroke(main_path, CLOUD, STROKE)
        + f'    <path android:pathData="{touch}" android:fillColor="{PARTIAL}"/>\n</vector>\n'
    )
    (res / "drawable/ic_launcher_foreground.xml").write_text(foreground, "utf-8")

    monochrome = head + stroke(main_path, "#FFFFFF", STROKE) + f'    <path android:pathData="{touch}" android:fillColor="#FFFFFF"/>\n</vector>\n'
    (res / "drawable/ic_launcher_monochrome.xml").write_text(monochrome, "utf-8")

    (res / "values/ic_launcher.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{PETROL}</color>\n</resources>\n',
        "utf-8",
    )
    (res / "mipmap-anydpi-v26/ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        "</adaptive-icon>\n",
        "utf-8",
    )


main()
